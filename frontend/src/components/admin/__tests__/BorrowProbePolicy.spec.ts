import { beforeEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import BorrowProbePolicy from '../BorrowProbePolicy.vue'
import type { BorrowTarget } from '@/api/admin/ticketBorrowing'
const api = vi.hoisted(() => ({ saveProbePolicy: vi.fn() }))
vi.mock('@/api/admin/ticketBorrowing', () => ({ ticketBorrowing: api }))
vi.mock('vue-i18n', () => ({ useI18n: () => ({ t: (key: string) => key, te: () => true }) }))
const target = (id = 11, revision = 1): BorrowTarget => ({ account_id: id, name: `Target ${id}`, enabled: true, revision: 2, ready: true, phase: 'waiting', reason: '', server_now: new Date().toISOString(), next_attempt_at: new Date().toISOString(), probe_policy: { revision, concurrency: 3, renew_before_seconds: 15 } })
const input = (w: ReturnType<typeof mount>, name: string) => w.get(`[data-testid="${name}"]`)
beforeEach(() => vi.clearAllMocks())
describe('per-target probe policy', () => {
  it('releases the standalone saving signal when unmounted and ignores its late result', async () => {
    let resolve!: (value: BorrowTarget) => void
    api.saveProbePolicy.mockReturnValueOnce(new Promise<BorrowTarget>(r => { resolve = r }))
    const w = mount(BorrowProbePolicy, { props: { target: target() } })
    await input(w, 'probe-concurrency').setValue(5)
    await input(w, 'probe-policy-save').trigger('click')
    expect(w.emitted('saving')?.at(-1)).toEqual([true])
    w.unmount()
    expect(w.emitted('saving')?.at(-1)).toEqual([false])
    resolve(target(11, 2)); await flushPromises()
    expect(w.emitted('saved')).toBeUndefined()
  })
  it('inherits live global values and supports an explicit account override', async () => {
    const inherited = { ...target(), probe_policy: { revision: 1, concurrency: 2, renew_before_seconds: 150, use_global: true, global_concurrency: 2, global_renew_before_seconds: 150 } }
    const w = mount(BorrowProbePolicy, { props: { target: inherited } })
    expect((input(w, 'probe-use-global').element as HTMLInputElement).checked).toBe(true)
    expect(input(w, 'probe-concurrency').attributes('disabled')).toBeDefined()
    await w.setProps({ target: { ...inherited, probe_policy: { ...inherited.probe_policy, concurrency: 4, global_concurrency: 4 } } })
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('4')
    expect(input(w, 'probe-policy-save').attributes('disabled')).toBeDefined()
    await input(w, 'probe-use-global').setValue(false)
    await input(w, 'probe-concurrency').setValue(3)
    api.saveProbePolicy.mockResolvedValue({ ...inherited, probe_policy: { ...inherited.probe_policy, revision: 2, concurrency: 3, use_global: false } })
    await input(w, 'probe-policy-save').trigger('click'); await flushPromises()
    expect(api.saveProbePolicy).toHaveBeenCalledWith(11, expect.objectContaining({ concurrency: 3, renew_before_seconds: 150, use_global: false }))
    w.unmount()
  })
  it('restores inheritance with the current global preview without replacing an override draft on polling', async () => {
    const customized = { ...target(), probe_policy: { revision: 1, concurrency: 3, renew_before_seconds: 90, use_global: false, global_concurrency: 2, global_renew_before_seconds: 180 } }
    const w = mount(BorrowProbePolicy, { props: { target: customized } })
    await input(w, 'probe-use-global').setValue(true)
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('2')
    await w.setProps({ target: { ...customized, probe_policy: { ...customized.probe_policy, global_concurrency: 4 } } })
    expect((input(w, 'probe-use-global').element as HTMLInputElement).checked).toBe(true)
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('4')
    api.saveProbePolicy.mockResolvedValue({ ...customized, probe_policy: { revision: 2, concurrency: 4, renew_before_seconds: 180, use_global: true, global_concurrency: 4, global_renew_before_seconds: 180 } })
    await input(w, 'probe-policy-save').trigger('click'); await flushPromises()
    expect(api.saveProbePolicy).toHaveBeenCalledWith(11, expect.objectContaining({ use_global: true }))
    expect(input(w, 'probe-policy-save').attributes('disabled')).toBeDefined()
    w.unmount()
  })
  it('uses concurrency 2 as the fallback when a policy is not loaded', () => {
    const w = mount(BorrowProbePolicy, { props: { target: { ...target(), probe_policy: undefined } } })
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('2')
    expect(input(w, 'probe-policy-save').attributes('disabled')).toBeDefined()
    w.unmount()
  })
  it('preserves a saved concurrency of 3 and saves only the selected target policy', async () => {
    const w = mount(BorrowProbePolicy, { props: { target: target() } })
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('3')
    await input(w, 'probe-concurrency').setValue(5)
    api.saveProbePolicy.mockResolvedValue({ ...target(), probe_policy: { revision: 2, concurrency: 5, renew_before_seconds: 30 } })
    await input(w, 'probe-policy-save').trigger('click'); await flushPromises()
    expect(api.saveProbePolicy).toHaveBeenCalledWith(11, { revision: 1, concurrency: 5, renew_before_seconds: 15, use_global: false })
    expect(w.emitted('saved')).toHaveLength(1)
    expect(w.emitted('saved')![0][0]).toMatchObject({ revision: 2, ready: true })
    w.unmount()
  })
  it('preserves drafts during polling and requires explicit reload on revision conflicts', async () => {
    const w = mount(BorrowProbePolicy, { props: { target: target() } })
    await input(w, 'probe-concurrency').setValue(4)
    await w.setProps({ target: { ...target(), inflight: 3 } })
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('4')
    await w.setProps({ target: target(11, 2) })
    expect(input(w, 'probe-policy-save').attributes('disabled')).toBeDefined()
    expect(w.get('[role="alert"]').text()).toContain('remoteChange')
    await input(w, 'probe-policy-revert').trigger('click')
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('3')
    expect(w.emitted('dirty')?.at(-1)).toEqual([false])
    w.unmount()
  })
  it.each([['probe-concurrency', 0], ['probe-concurrency', 33], ['probe-concurrency', 1.5]])('rejects invalid %s = %s', async (name, value) => {
    const w = mount(BorrowProbePolicy, { props: { target: target() } })
    await input(w, name as string).setValue(value)
    expect(input(w, name as string).attributes('aria-invalid')).toBe('true')
    expect(w.text()).toContain(name === 'probe-concurrency' ? 'probePolicy.concurrencyError' : 'probePolicy.renewError')
    expect(input(w, 'probe-policy-save').attributes('disabled')).toBeDefined()
    expect(api.saveProbePolicy).not.toHaveBeenCalled(); w.unmount()
  })
  it('accepts maximum concurrency without a renewal control', async () => {
    const w = mount(BorrowProbePolicy, { props: { target: target() } })
    await input(w, 'probe-concurrency').setValue(32)
    expect(input(w, 'probe-policy-save').attributes('disabled')).toBeUndefined(); w.unmount()
  })
  it('keeps failed drafts and ignores a late response after switching targets', async () => {
    const w = mount(BorrowProbePolicy, { props: { target: target() } })
    await input(w, 'probe-concurrency').setValue(4)
    api.saveProbePolicy.mockRejectedValueOnce({ reason: 'borrow_configuration_conflict' })
    await input(w, 'probe-policy-save').trigger('click'); await flushPromises()
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('4')
    let resolve!: (value: BorrowTarget) => void
    api.saveProbePolicy.mockReturnValue(new Promise<BorrowTarget>(r => { resolve = r }))
    await input(w, 'probe-policy-save').trigger('click')
    await w.setProps({ target: target(22) })
    resolve(target(11, 2)); await flushPromises()
    expect(w.emitted('saved')).toBeUndefined()
    expect((input(w, 'probe-concurrency').element as HTMLInputElement).value).toBe('3')
    w.unmount()
  })
})
