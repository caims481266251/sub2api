import { describe, it, expect, vi } from 'vitest'
import { mount } from '@vue/test-utils'
import BorrowSourceRotation from '../BorrowSourceRotation.vue'
import type { BorrowRotationState } from '@/api/admin/ticketBorrowing'
vi.mock('vue-i18n', () => ({useI18n: () => ({t: (key: string) => key})}))
const state = (revision = 2): BorrowRotationState => ({account_id: 11, role: 'source', revision, automatic: false, interval_seconds: 60, phase: 'idle', reason: '', environment_version: 1, server_now: new Date().toISOString()})
const mountPanel = (s?: BorrowRotationState) => mount(BorrowSourceRotation, {props: {accountId: 11, name: 'source', canRotate: true, hasBinding: true, state: s, busy: false, running: true, loaded: true}})
describe('source borrowing environment rotation', () => {
 it.each([0, 86401, 1.5, ''])('shows invalid interval %s before a save can be submitted', async value => {
  const w = mountPanel(state())
  await w.get('[data-testid="rotation-interval"]').setValue(value)
  expect(w.get('[data-testid="rotation-interval"]').attributes('aria-invalid')).toBe('true')
  expect(w.text()).toContain('ticketBorrowing.rotation.intervalError')
  expect(w.get('[data-testid="rotation-save"]').attributes('disabled')).toBeDefined()
  expect(w.emitted('save')).toBeUndefined()
  // Invalid automatic settings must not disable an independent manual rotation.
  expect(w.get('[data-testid="rotation-now"]').attributes('disabled')).toBeUndefined()
  w.unmount()
 })
 it('defaults to 60 seconds with automatic rotation off and saves an explicit policy', async () => {
  const w = mountPanel()
  expect((w.get('[data-testid="rotation-interval"]').element as HTMLInputElement).value).toBe('60')
  expect((w.get('[data-testid="rotation-auto"]').element as HTMLInputElement).checked).toBe(false)
  await w.get('[data-testid="rotation-auto"]').setValue(true)
  await w.get('[data-testid="rotation-save"]').trigger('click')
  expect(w.emitted('save')?.[0]).toEqual([{revision: 0, automatic: true, interval_seconds: 60}])
  w.unmount()
 })
 it('retains drafts on polling, blocks stale saves, and explicitly reverts to the new policy', async () => {
  const w = mountPanel(state())
  await w.get('[data-testid="rotation-interval"]').setValue(90)
  await w.setProps({state: {...state(), phase: 'draining', active_job: 'job'}})
  expect((w.get('[data-testid="rotation-interval"]').element as HTMLInputElement).value).toBe('90')
  expect(w.get('[data-testid="rotation-now"]').attributes('disabled')).toBeDefined()
  await w.setProps({state: {...state(3), interval_seconds: 120}})
  expect(w.get('[data-testid="rotation-save"]').attributes('disabled')).toBeDefined()
  expect(w.find('[role="alert"]').exists()).toBe(true)
  await w.get('[data-testid="rotation-revert"]').trigger('click')
  expect((w.get('[data-testid="rotation-interval"]').element as HTMLInputElement).value).toBe('120')
  expect(w.emitted('dirty')?.at(-1)).toEqual([false])
  w.unmount()
 })
 it('accepts the saved revision and pauses automatic scheduling but permits manual source rotation while paused', async () => {
  const w = mountPanel(state())
  await w.get('[data-testid="rotation-auto"]').setValue(true)
  await w.setProps({state: {...state(3), automatic: true}})
  expect(w.get('[data-testid="rotation-save"]').attributes('disabled')).toBeDefined()
  expect(w.find('[role="alert"]').exists()).toBe(false)
  await w.setProps({running: false})
  expect(w.get('[data-testid="rotation-now"]').attributes('disabled')).toBeUndefined()
  expect(w.text()).toContain('ticketBorrowing.rotation.pausedHint')
  await w.setProps({running: true, loaded: false})
  expect(w.get('[data-testid="rotation-now"]').attributes('disabled')).toBeDefined()
  await w.setProps({loaded: true})
  await w.get('[data-testid="rotation-now"]').trigger('click')
  expect(w.emitted('rotate')).toHaveLength(1)
  w.unmount()
 })
})

it('blocks immediate rotation and shows the server reason for an unhealthy source', async () => {
 const w=mountPanel(state())
 await w.setProps({canRotate:false,rotationUnavailableReason:'source_account_unavailable'})
 expect(w.get('[data-testid="rotation-now"]').attributes('disabled')).toBeDefined()
 expect(w.text()).toContain('ticketBorrowing.reasons.source_account_unavailable')
 w.unmount()
})
